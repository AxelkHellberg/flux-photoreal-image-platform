#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
if [[ -f "$ROOT_DIR/.env" ]]; then
  set -a
  # shellcheck disable=SC1091
  source "$ROOT_DIR/.env"
  set +a
fi

POSTGRES_DB="${POSTGRES_DB:-image_platform}"
POSTGRES_USER="${POSTGRES_USER:-postgres}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-postgres}"
RUNPOD_REVERSE_TUNNEL_POSTGRES_PORT="${RUNPOD_REVERSE_TUNNEL_POSTGRES_PORT:-15432}"
RUNPOD_REVERSE_TUNNEL_REDIS_PORT="${RUNPOD_REVERSE_TUNNEL_REDIS_PORT:-16379}"
RUNPOD_REVERSE_TUNNEL_API_PORT="${RUNPOD_REVERSE_TUNNEL_API_PORT:-18000}"

export DATABASE_URL="postgresql+psycopg://${POSTGRES_USER}:${POSTGRES_PASSWORD}@127.0.0.1:${RUNPOD_REVERSE_TUNNEL_POSTGRES_PORT}/${POSTGRES_DB}"
export REDIS_URL="redis://127.0.0.1:${RUNPOD_REVERSE_TUNNEL_REDIS_PORT}/0"
export PUBLIC_API_BASE_URL="http://127.0.0.1:${RUNPOD_REVERSE_TUNNEL_API_PORT}"

unset WORKER_TUNNEL_SSH_HOST
unset WORKER_TUNNEL_SSH_USER
unset WORKER_TUNNEL_SSH_PORT
unset WORKER_TUNNEL_LOCAL_POSTGRES_PORT
unset WORKER_TUNNEL_LOCAL_REDIS_PORT
unset WORKER_TUNNEL_PRIVATE_KEY_LOCAL_PATH
unset WORKER_TUNNEL_KEY_REMOTE_PATH

cd "$ROOT_DIR"
bash infra/scripts/deploy-worker.sh
